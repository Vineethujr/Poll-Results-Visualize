"""
report_generator.py - PDF & CSV Report Generator
Compiles automated executive PDF summaries using FPDF2 and handles CSV export formatting.
"""

from typing import List, Dict, Any, Optional
import os
import pandas as pd
from fpdf import FPDF

class SurveyReportPDF(FPDF):
    """Custom FPDF class for structured survey analytical reports."""
    def header(self):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(30, 41, 59)
        self.cell(0, 10, "Poll & Survey Results Executive Report", border=False, new_x="LMARGIN", new_y="NEXT", align="C")
        self.set_font("Helvetica", "I", 10)
        self.set_text_color(100, 116, 139)
        self.cell(0, 6, "Automated Descriptive Insights & Demographic Analysis", border=False, new_x="LMARGIN", new_y="NEXT", align="C")
        self.ln(5)
        # Decorative divider line
        self.set_draw_color(37, 99, 235)
        self.set_line_width(0.8)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by Poll Results Visualizer", align="C")

def generate_pdf_report(
    output_pdf_path: str,
    share_df: pd.DataFrame,
    insights: List[str],
    metrics: Dict[str, Any],
    static_chart_path: Optional[str] = None
) -> str:
    """
    Generates a professional executive PDF report summarizing survey results.
    """
    pdf = SurveyReportPDF(orientation="P", unit="mm", format="A4")
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)
    
    # 1. Executive Summary Metrics Box
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(37, 99, 235)
    pdf.cell(0, 8, "1. Executive KPI Summary", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(51, 65, 85)
    
    kpi_text = (
        f"Total Sample Size: {metrics.get('sample_size', 'N/A'):,} respondents  |  "
        f"Valid Votes Analyzed: {metrics.get('valid_votes', 'N/A'):,}  |  "
        f"Top Option: {metrics.get('top_option', 'N/A')} ({metrics.get('top_share', 'N/A')}%)"
    )
    pdf.set_fill_color(241, 245, 249)
    pdf.cell(0, 8, kpi_text, border=True, fill=True, new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.ln(5)
    
    # 2. Key Findings & Automated Narrative Takeaways
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(37, 99, 235)
    pdf.cell(0, 8, "2. Key Analytical Takeaways", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    
    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(51, 65, 85)
    for insight in insights:
        # Strip simple markdown bold formatting for clean PDF rendering
        clean_insight = insight.replace("**", "")
        pdf.multi_cell(0, 6, f"- {clean_insight}")
        pdf.ln(1)
        
    pdf.ln(4)
    
    # 3. Share & Results Table
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(37, 99, 235)
    pdf.cell(0, 8, "3. Vote Share Breakdown", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    
    # Table Header
    col_widths = [80, 35, 35, 40]
    headers = ["Option / Response", "Votes", "Share (%)", "Cumulative (%)"]
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_fill_color(226, 232, 240)
    pdf.set_text_color(30, 41, 59)
    for i, h in enumerate(headers):
        pdf.cell(col_widths[i], 7, h, border=1, fill=True, align="C")
    pdf.ln()
    
    # Table Rows
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(71, 85, 105)
    for _, row in share_df.iterrows():
        pdf.cell(col_widths[0], 6, str(row["Option"]), border=1)
        pdf.cell(col_widths[1], 6, f"{int(row['Votes']):,}", border=1, align="C")
        pdf.cell(col_widths[2], 6, f"{row['Share (%)']}%", border=1, align="C")
        pdf.cell(col_widths[3], 6, f"{row['Cumulative (%)']}%", border=1, align="C")
        pdf.ln()
        
    pdf.ln(6)
    
    # 4. Embedded Static Chart Image if provided
    if static_chart_path and os.path.exists(static_chart_path):
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(37, 99, 235)
        pdf.cell(0, 8, "4. Graphical Distribution Overview", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)
        # Embed chart image centered
        pdf.image(static_chart_path, x=20, w=170)
        
    # Ensure destination folder exists
    os.makedirs(os.path.dirname(output_pdf_path), exist_ok=True)
    pdf.output(output_pdf_path)
    return output_pdf_path

def export_summary_to_csv(df: pd.DataFrame, output_csv_path: str) -> str:
    """Exports any analytical summary table to CSV."""
    os.makedirs(os.path.dirname(output_csv_path), exist_ok=True)
    df.to_csv(output_csv_path, index=True if df.index.name else False)
    return output_csv_path
